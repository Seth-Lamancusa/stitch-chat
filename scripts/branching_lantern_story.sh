#!/usr/bin/env bash
# Prints a short story about a lantern that remembers every path not taken.

cat <<'EOF'
The Branching Lantern

In the city of Lower Quill, messages did not travel in straight lines. They forked—one argument becoming three replies, one apology spawning seven drafts nobody sent. Couriers called these splits "threads," and they tangled in the alleyways like ivy until the post office gave up and hired archivists instead.

Nadia Keene kept the lantern on Threadneedle Court. It was not lit by oil or filament but by unanswered questions: a soft amber when someone wondered "what if," a sharp white when they almost pressed send and pulled back. Every night she walked the forks, reading the glow off brick walls, tying silk ribbons at junctions so midnight walkers would not lose the way home.

Her apprentice, Jules, believed threads were mistakes waiting to be deleted. "Pick one path," Jules said, sharpening a quill that had never written a true letter. "Reality is a single line. The rest is noise."

Old Pell, who had delivered mail when the forks were only rumors, laughed from the stoop. "Noise is how the city breathes. Cut every branch and you suffocate the block."

On the night the Great Silence fell—a hush so complete that even the tram wires stopped humming—the lantern guttered. Every thread at once had frozen mid-choice: proposals half-written, goodbyes stuck on the tongue, code reviews left in "draft." Nadia climbed to the roof where the lantern hung and found its flame pinched to a pinprick, fed by a million paused moments and no forward motion.

Jules brought a shears from the archive. "One cut," they said. "One canonical thread. The lantern will burn clean again."

Nadia stopped their hand. "If we choose for them, the silence wins. We don't merge threads—we light the crossings so people can walk them when they're ready."

She opened the ledger she had kept since her first week on the court—not to record destinations, but to map how branches rejoined. Here, three arguments had converged on coffee and a truce. There, two rival inventions had merged into a bridge. She read the crossings aloud into the dark. The lantern drank each story and threw warmth down the alleys, not erasing the forks but making them visible: amber paths you could follow without shame.

House by house, windows brightened. A woman finished her apology. A boy sent the question he had hoarded for a year. Two engineers on opposite branches realized they had been fixing the same bug from different sides and met at the ribbon Nadia had tied years ago, still faded but true.

Jules tied their first ribbon at a junction they had once called waste. "I thought the extra paths were clutter," they said. "They're more like spare keys."

Pell delivered one letter by foot—the last he would carry, he claimed, though he had said that every autumn. It was addressed to no one and everyone: Thank you for leaving the side doors open.

Dawn came not as a single sunline but as many small yeses—the sound of threads moving again, not collapsing into one story but braiding where it mattered. Nadia trimmed the wick. The lantern settled to its usual amber, steady enough to read by.

They say if you stand on Threadneedle Court when rain smells like ink, the lantern will sway toward the fork you are afraid to enter—not to push you, but to remind you that every path worth walking was once a draft, and every reunion begins with someone willing to carry a light into the tangle.

The end.

EOF
